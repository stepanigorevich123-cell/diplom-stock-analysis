import pandas as pd
import numpy as np

# ============================================================
# ШАГ 1: Загружаем данные
# ============================================================

df = pd.read_csv("D:/diplom/data/weekly_prices.csv")
df["begin"] = pd.to_datetime(df["begin"])
print(f"Исходно: {df['ticker'].nunique()} акций, {len(df)} строк")

# ============================================================
# ШАГ 2: Обрезаем период до февраля 2026
# ============================================================

df = df[df["begin"] <= "2026-02-28"]
print(f"После обрезки периода: {df['ticker'].nunique()} акций, {len(df)} строк")

# ============================================================
# ШАГ 3: Загружаем список акций и исключаем иностранные бумаги
# ISIN иностранных бумаг не начинается на RU
# Пример: OKEY (US6708...), VEON-RX (BMG9349...)
# ============================================================

stocks_list = pd.read_csv("D:/diplom/data/stocks_list.csv")
foreign = stocks_list[~stocks_list["ISIN"].str.startswith("RU")]["SECID"].tolist()
print(f"\nИностранные бумаги (исключаем): {foreign}")

df = df[~df["ticker"].isin(foreign)]
print(f"После исключения иностранных: {df['ticker'].nunique()} акций")

# ============================================================
# ШАГ 4: Исключаем привилегированные акции
# Они дублируют обыкновенные и имеют другую динамику цен
# Признак: тикер заканчивается на P (SBERP, TATNP и т.д.)
# Исключения: GAZAP, SIBN — это не префы, просто названия
# ============================================================

# Список префов которые точно исключаем
# Список реальных префов — только те у кого в названии есть "ап" или "п"
real_prefs = stocks_list[
    (stocks_list["SECID"].str.endswith("P")) & 
    (~stocks_list["SECID"].isin(["GAZP", "RASP", "NKHP", "NMTP", "SPBE", "SOFL", "SFIN", "SGZH", "SMLT", "SVCB", "SVAV", "SNGS", "SIBN", "SELG"]))
]["SECID"].tolist()
prefs = real_prefs
# Убираем исключения (компании у которых P не означает префы)
not_prefs = ["GAZAP"]  # ГАЗ ап — это реально преф, оставим в списке на исключение
print(f"\nПривилегированные акции ({len(prefs)} шт): {prefs}")

df = df[~df["ticker"].isin(prefs)]
print(f"После исключения префов: {df['ticker'].nunique()} акций")

# ============================================================
# ШАГ 5: Исключаем период закрытия биржи
# МосБиржа была закрыта 25 февраля — 24 марта 2022
# В этот период цены нерыночные — биржа не работала
# ============================================================

mask_closed = (df["begin"] >= "2022-02-25") & (df["begin"] <= "2022-03-25")
df = df[~mask_closed]
print(f"\nПосле исключения периода закрытия биржи: {len(df)} строк")

# ============================================================
# ШАГ 6: Фильтр по ликвидности
# Amihud ratio = |доходность| / объём торгов в рублях
# Для микроликвидных акций (ЗИЛ, ЗВЕЗДА и т.д.) объём почти ноль
# Оставляем только акции со средним недельным оборотом > 1 млн руб
# ============================================================

avg_value = df.groupby("ticker")["value"].median()
liquid_tickers = avg_value[avg_value > 1_000_000].index.tolist()
illiquid = avg_value[avg_value <= 1_000_000].index.tolist()

print(f"\nМикроликвидные (исключаем, оборот < 1 млн руб/нед): {illiquid}")
df = df[df["ticker"].isin(liquid_tickers)]
print(f"После фильтра ликвидности: {df['ticker'].nunique()} акций")

# ============================================================
# ШАГ 7: Фильтр по минимальному количеству наблюдений
# Нужно минимум 100 недель данных чтобы оценить коэффициенты
# (это примерно 2 года)
# ============================================================

obs_count = df.groupby("ticker")["begin"].count()
enough_obs = obs_count[obs_count >= 100].index.tolist()
df = df[df["ticker"].isin(enough_obs)]
print(f"После фильтра минимум 100 недель: {df['ticker'].nunique()} акций")

# ============================================================
# ШАГ 8: Считаем недельную доходность
# Доходность = (цена_закрытия / цена_закрытия_прошлой_недели) - 1
# Это простая доходность, стандартная в факторных моделях
# ============================================================

df = df.sort_values(["ticker", "begin"])
df["return"] = df.groupby("ticker")["close"].pct_change()

# Убираем экстремальные выбросы (доходность > 100% или < -50% за неделю)
# Это скорее всего ошибки данных или корпоративные события
before = len(df)
df = df[df["return"].between(-0.5, 1.0)]
print(f"\nУбрано выбросов доходности: {before - len(df)} строк")

# ============================================================
# ШАГ 9: Считаем Amihud ratio
# Amihud = |доходность| / оборот в рублях
# Чем выше — тем менее ликвидна акция
# Это будет контрольная переменная в регрессии
# ============================================================

df["amihud"] = df["return"].abs() / df["value"]
# Убираем бесконечные значения (когда value = 0)
df["amihud"] = df["amihud"].replace([np.inf, -np.inf], np.nan)

# ============================================================
# ШАГ 10: Добавляем Post dummy
# Post = 1 для всех наблюдений после 24 февраля 2022
# Post = 0 до этой даты
# Это главная переменная структурного сдвига
# ============================================================

df["post"] = (df["begin"] >= "2022-02-24").astype(int)

# ============================================================
# ШАГ 11: Сохраняем
# ============================================================

df.to_csv("D:/diplom/data/weekly_prices_clean.csv", index=False)

print(f"\n=== ИТОГ ===")
print(f"Чистых акций: {df['ticker'].nunique()}")
print(f"Строк: {len(df)}")
print(f"Период: {df['begin'].min().date()} — {df['begin'].max().date()}")
print(f"Pre-period (post=0): {(df['post']==0).sum()} строк")
print(f"Post-period (post=1): {(df['post']==1).sum()} строк")
print(f"\nФайл сохранён: data/weekly_prices_clean.csv")
print(f"\nСписок финальных акций:")
print(sorted(df['ticker'].unique().tolist()))