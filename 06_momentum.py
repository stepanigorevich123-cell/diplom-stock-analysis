import pandas as pd
import numpy as np

# ============================================================
# MOMENTUM — доходность акции за прошлые 3–12 месяцев
#
# Jegadeesh и Titman (1993) показали что акции которые
# хорошо росли последние 3–12 месяцев продолжают расти.
# Это контрольная переменная в нашей регрессии.
#
# Стандартная формула: доходность за недели t-52 до t-4
# (пропускаем последний месяц чтобы избежать reversal —
# краткосрочного разворота который искажает моментум)
# ============================================================

df = pd.read_csv("D:/diplom/data/weekly_prices_clean.csv")
df["begin"] = pd.to_datetime(df["begin"])
df = df.sort_values(["ticker", "begin"]).reset_index(drop=True)

print(f"Загружено: {df['ticker'].nunique()} акций, {len(df)} строк")

# ============================================================
# ШАГ 1: Считаем моментум
#
# Моментум = накопленная доходность за недели с t-52 по t-4
# t-52 = примерно год назад
# t-4  = примерно месяц назад (пропускаем последний месяц)
#
# Накопленная доходность = произведение (1 + r_i) для всех недель
# Пример: +2%, +3%, -1% → 1.02 * 1.03 * 0.99 - 1 = 4.0%
# ============================================================

print("\nСчитаем моментум для каждой акции...")

results = []
for ticker, group in df.groupby("ticker"):
    group = group.sort_values("begin").copy()
    returns = group["return"].values
    n = len(returns)
    momentum = np.full(n, np.nan)

    for i in range(52, n):
        # Берём недели с i-52 до i-4
        window = returns[max(0, i-52):i-4]
        if len(window) >= 20:  # минимум 20 недель данных
            momentum[i] = np.prod(1 + window) - 1

    group["momentum"] = momentum
    results.append(group)

df = pd.concat(results, ignore_index=True)

# ============================================================
# ШАГ 2: Проверяем результат
# ============================================================

valid = df["momentum"].notna().sum()
print(f"Строк с моментумом: {valid} из {len(df)}")
print(f"Пропущено NaN: {df['momentum'].isna().sum()} (первые ~52 недели каждой акции)")
print("\nСтатистика моментума:")
print(df["momentum"].describe().round(4))

# ============================================================
# ШАГ 3: Проверяем на примере Сбербанка
# ============================================================

sber = df[df["ticker"] == "SBER"][["begin", "return", "momentum"]].dropna()
print(f"\nСбербанк — первые 5 строк с моментумом:")
print(sber.head())
print(f"\nСбербанк — моментум в феврале 2022:")
print(sber[sber["begin"].between("2022-01-01", "2022-03-01")])

# ============================================================
# ШАГ 4: Исключаем финансовые компании
#
# Банки и финансовые компании исключаются потому что их
# leverage (долг/активы) несопоставим с нефинансовыми фирмами.
# Депозиты клиентов = "долг" на балансе банка, поэтому
# leverage банка 0.9+ это норма, а не признак проблем.
# Стандарт: Fama и French (1992) делали то же самое.
# ============================================================

financial_tickers = [
    "SBER",  # Сбербанк
    "VTBR",  # ВТБ
    "BSPB",  # Банк Санкт-Петербург
    "T",     # Т-Банк
    "SVCB",  # Совкомбанк
    "CBOM",  # МКБ
    "MOEX",  # Московская биржа
    "SFIN",  # ЭсЭфАй
    "RENI",  # Ренессанс Страхование
    "LEAS",  # Европлан
    "MGKL",  # МГКЛ
    "SPBE",  # СПБ Биржа
]

print(f"\n=== ИСКЛЮЧАЕМ ФИНАНСОВЫЕ КОМПАНИИ ===")
before = df["ticker"].nunique()
df = df[~df["ticker"].isin(financial_tickers)]
after = df["ticker"].nunique()
print(f"Исключено: {financial_tickers}")
print(f"Акций до: {before}, после: {after}")

# ============================================================
# ШАГ 5: Сохраняем
# ============================================================

df.to_csv("D:/diplom/data/weekly_prices_clean.csv", index=False)
print(f"\n=== ИТОГ ===")
print(f"Акций: {df['ticker'].nunique()}")
print(f"Строк: {len(df)}")
print(f"Период: {df['begin'].min().date()} — {df['begin'].max().date()}")
print(f"Файл сохранён: data/weekly_prices_clean.csv")

